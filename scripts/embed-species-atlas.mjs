import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const atlas = fileURLToPath(new URL('../packages/dsh-whale-companion/assets/whale-species-atlas.webp', import.meta.url))
const target = fileURLToPath(new URL('../packages/dsh-whale-companion/src/client/species-atlas.ts', import.meta.url))
const dataUrl = `data:image/webp;base64,${readFileSync(atlas).toString('base64')}`

writeFileSync(target, `// Generated by scripts/embed-species-atlas.mjs.\nexport const WHALE_SPECIES_ATLAS = ${JSON.stringify(dataUrl)}\n`)
console.log(`Embedded ${dataUrl.length} characters into ${target}`)
