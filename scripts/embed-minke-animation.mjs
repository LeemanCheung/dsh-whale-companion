import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const sprite = fileURLToPath(new URL('../packages/dsh-whale-companion/assets/minke-swim-sprite.png', import.meta.url))
const target = fileURLToPath(new URL('../packages/dsh-whale-companion/src/client/minke-swim-sprite.ts', import.meta.url))
const dataUrl = `data:image/png;base64,${readFileSync(sprite).toString('base64')}`

writeFileSync(target, `// Generated by scripts/embed-minke-animation.mjs.\nexport const MINKE_SWIM_SPRITE = ${JSON.stringify(dataUrl)}\n`)
console.log(`Embedded ${dataUrl.length} characters into ${target}`)
